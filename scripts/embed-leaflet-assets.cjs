/**
 * Inlines Leaflet 1.9.4 into lib/leafletBundledAssets.ts for offline WebView maps
 * (no CDN latency on Explore / city map).
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const cssPath = path.join(root, 'assets', 'map', 'leaflet.css');
const jsPath = path.join(root, 'assets', 'map', 'leaflet.js');
const outPath = path.join(root, 'lib', 'leafletBundledAssets.ts');

if (!fs.existsSync(cssPath) || !fs.existsSync(jsPath)) {
  console.error('Run: curl/unpkg download to assets/map/leaflet.css and leaflet.js first');
  process.exit(1);
}

const css = fs.readFileSync(cssPath, 'utf8');
const js = fs.readFileSync(jsPath, 'utf8');

const out = `/** Generated by scripts/embed-leaflet-assets.cjs — do not edit by hand. */
export const LEAFLET_CSS_INLINE: string = ${JSON.stringify(css)};
export const LEAFLET_JS_INLINE: string = ${JSON.stringify(js)};
`;

fs.writeFileSync(outPath, out, 'utf8');
console.log(`Wrote ${outPath} (${(out.length / 1024).toFixed(0)} KB)`);
